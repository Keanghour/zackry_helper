# zackry_cli/testtool/storage.py
#
# Reads and writes config/endpoints.json (the APIs and endpoints to test)
# and keeps config/.env.example in sync with the env var NAMES those
# configs reference. No secret value is ever written by this module.

import json
from pathlib import Path
from typing import Dict

from pydantic import ValidationError

from zackry_cli.testtool.config import APIConfig

CONFIG_DIR = Path("config")
CONFIG_FILE = CONFIG_DIR / "endpoints.json"
ENV_EXAMPLE_FILE = CONFIG_DIR / ".env.example"

ApiRegistry = Dict[str, APIConfig]


class ConfigError(Exception):
    """Raised when config/endpoints.json exists but cannot be read."""


def load_apis() -> ApiRegistry:
    """Read config/endpoints.json. Returns {} if it does not exist yet."""
    if not CONFIG_FILE.exists():
        return {}

    try:
        raw = json.loads(CONFIG_FILE.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise ConfigError(f"{CONFIG_FILE} is not valid JSON: {error}") from error

    apis: ApiRegistry = {}

    for name, data in raw.items():
        try:
            apis[name] = APIConfig.model_validate(data)
        except ValidationError as error:
            raise ConfigError(f"{CONFIG_FILE}: API '{name}' is invalid:\n{error}") from error

    return apis


def save_apis(apis: ApiRegistry) -> None:
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)

    data = {name: api.model_dump() for name, api in apis.items()}
    CONFIG_FILE.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")

    write_env_example(apis)


def collect_env_names(apis: ApiRegistry):
    names = []

    for api in apis.values():
        for name in api.env_names():
            if name not in names:
                names.append(name)

    return names


def write_env_example(apis: ApiRegistry) -> None:
    """
    Regenerate config/.env.example from the current configs: one line per
    referenced env var name, value left empty. Safe to run every time,
    never touches the real .env file.
    """
    names = collect_env_names(apis)

    CONFIG_DIR.mkdir(parents=True, exist_ok=True)

    lines = [
        "# Generated by `zackry test`.",
        "# Copy the variables you need into your real .env file and fill in the values.",
        "",
    ]

    if names:
        lines += [f"{name}=" for name in names]
    else:
        lines.append("# (no APIs configured yet)")

    ENV_EXAMPLE_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")